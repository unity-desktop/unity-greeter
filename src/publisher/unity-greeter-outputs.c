#include "unity-greeter-outputs.h"

#include <gtk/gtk.h>

#include "unity-greeter-publish.h"

void
unity_greeter_outputs_publish (void)
{
  GString *outputs = g_string_new ("# Generated by unity-greeter-publisher.\n");

  GListModel *monitors = gdk_display_get_monitors (gdk_display_get_default ());
  for (guint i = 0; i < g_list_model_get_n_items (monitors); i++)
    {
      g_autoptr (GdkMonitor) monitor = g_list_model_get_item (monitors, i);
      const gchar *connector = gdk_monitor_get_connector (monitor);
      if (connector != NULL)
        g_string_append_printf (outputs, "\n[output:%s]\nscale = %.6f\n",
                                connector, gdk_monitor_get_scale (monitor));
    }

  g_autoptr (GBytes) contents = g_string_free_to_bytes (outputs);
  g_autoptr (GError) error = NULL;
  if (!unity_greeter_publish_bytes (UNITY_GREETER_PUBLISH_OUTPUTS, contents, &error))
    g_warning ("%s: %s", UNITY_GREETER_PUBLISH_OUTPUTS, error->message);
}
